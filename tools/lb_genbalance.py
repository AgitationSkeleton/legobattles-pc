#!/usr/bin/env python3
"""Generate the bundled balance-patch tables for the port.

The three community balance mods change `BP/Entities.ebp` and nothing else
(`docs/101`). This extracts that one file from each mod ROM, decompresses it,
diffs it against the retail blueprint, and emits the differences as a C table
the port compiles in.

**What is bundled is a list of (offset, byte) runs, not anyone's ROM.** The
diffs are numeric tweaks to retail data; the mods' authors are credited in the
generated header and in `docs/101`. Run this, do not hand-edit the output.

    python tools/lb_genbalance.py --out port/runner/src/lb_balance_data.h
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lb_comp
import nds_extract

# LB_MODS_DIR, else roms/lbmods two levels above this checkout.
MODS_DIR = os.environ.get("LB_MODS_DIR") or os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "roms", "lbmods")

# slot order must match the overlay's dropdown: 1 Rebalance, 2 FactionWars,
# 3 Funlite, 4 FunLite2. Slot 0 is vanilla and has no table.
# (name, rom, version shown in the dropdown) -- docs/426.
MODS = [
    ("Rebalance",   "REbalance_MapBase.nds", "1.15.2"),
    ("FactionWars", "FactionWars_MapBase.nds", "1.2"),
    ("Funlite",     "FUNLite_MapBase.nds", "1.7.2"),
    ("FunLite2",    "FunLite2-G(PvE).nds", "(PvE)"),
    # docs/426: compressed Entities.ebp files, not ROMs.
    ("FactionWars2", "factionwars 2.0.1.ebp", "2.0.1"),
    ("Vanilplus",   "VanilPlus1.2.1.ebp", "1.2.1"),
    ("Fusion",      "fusion 1-2.ebp", "1.2"),
    # Appended, so every stored slot keeps meaning the same pack. A bare
    # Entities.ebp in its own directory (docs/426).
    ("Rebalance2",  "rebalance-1.18.1/Entities.ebp", "1.18.1"),
]
# Dropdown names where "<name> <version>" is not it.
DISPLAY = {"FactionWars2": "FactionWars 2.0.1", "Vanilplus": "Vanil+ 1.2.1",
           "Rebalance2": "Rebalance 1.18.1"}
BASE = "VANILLA_MapBase.nds"
TARGET = "BP/Entities.ebp"


def blueprint_from_rom(path):
    """Decompressed BP/Entities.ebp out of an NDS image.

    Same FNT/FAT walk tools/lb_moddiff.py uses, so the two agree by
    construction about which bytes belong to which path.
    """
    with open(path, "rb") as fh:
        raw = fh.read()
    if path.lower().endswith(".ebp"):   # a bare Entities.ebp, raw or COMP
        return raw if raw[:4] == b"BPNZ" else lb_comp.comp_decode(raw)
    fnt_off, fnt_len = struct.unpack("<II", raw[0x40:0x48])
    fat_off, fat_len = struct.unpack("<II", raw[0x48:0x50])
    paths, _dirs = nds_extract.parse_fnt(raw[fnt_off:fnt_off + fnt_len])
    fat = nds_extract.parse_fat(raw[fat_off:fat_off + fat_len])
    for fid, name in paths.items():
        if name.replace("\\", "/").endswith(TARGET) and fid < len(fat):
            start, end = fat[fid]
            return lb_comp.comp_decode(raw[start:end])
    raise SystemExit("no %s in %s" % (TARGET, path))


def runs(base, mod):
    """Contiguous (offset, bytes) differences, base -> mod."""
    if len(base) != len(mod):
        raise SystemExit("length mismatch %d vs %d" % (len(base), len(mod)))
    out = []
    i = 0
    n = len(base)
    while i < n:
        if base[i] == mod[i]:
            i += 1
            continue
        start = i
        while i < n and base[i] != mod[i]:
            i += 1
        out.append((start, mod[start:i]))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="port/runner/src/lb_balance_data.h")
    ap.add_argument("--mods-dir", default=MODS_DIR)
    args = ap.parse_args()

    base = blueprint_from_rom(os.path.join(args.mods_dir, BASE))
    print("vanilla blueprint: %d bytes" % len(base))

    tables = []
    for name, rom, ver in MODS:
        mod = blueprint_from_rom(os.path.join(args.mods_dir, rom))
        r = runs(base, mod)
        changed = sum(len(b) for _, b in r)
        print("  %-12s %5d runs, %6d bytes changed" % (name, len(r), changed))
        tables.append((name, r, changed, ver))

    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("""// lb_balance_data.h - bundled balance-patch differences.
//
// GENERATED by tools/lb_genbalance.py. Do not hand-edit; re-run the generator.
//
// These are numeric differences against the retail BP/Entities.ebp, nothing
// more: no code, no assets, no ROM. The three balance mods change that one file
// and nothing else (docs/101), so a list of changed bytes reproduces them.
//
// CREDIT. The balance work is not this project's.
//
//   Rebalance Patch for Lego Battles
//     https://github.com/Ryncat/LegoBattlesRebalancePatch
//     Ryncat            - developed every version of the patch and its notes
//     Alpha47           - development help; patches 1.13.1 and 1.14.1
//     Opiter09          - the Entities Editor the patch was built with
//                         https://github.com/opiter09/Entities-Editor
//     The Chinese team  - Crystal Tile 2, used to install it
//     The LEGO Battles community - testing and development
//
//   FactionWars and Funlite are community romhacks distributed with the same
//   scope: entity statistics only.
//
//   Credits as the preset names them:
//     FactionWars by Alpha47
//     Vanil+ by RynCat
//     Rebalance by RynCat
//     FunLite by Dream-Foxtrot
//     Fusion by NinjaGoat
//
//   FunLite2 (PvE) - the FUNLite line's second release; its author is
//     dream-foxtrot (Foxtrot), who also made FUNLite. Only its
//     BP/Entities.ebp is used here.
//
// Ryncat's README asks that all players in a multiplayer game use the same
// patch. The port treats the balance selection as lobby-carried for that
// reason (docs/86).

#ifndef LB_BALANCE_DATA_H
#define LB_BALANCE_DATA_H

#include <stdint.h>

typedef struct LbBalanceRun {
    uint32_t offset;
    uint32_t length;
    const uint8_t* bytes;
} LbBalanceRun;

typedef struct LbBalanceTable {
    const char* name;
    const LbBalanceRun* runs;
    uint32_t run_count;
    uint32_t byte_count;
    uint32_t blueprint_size;   /* the decompressed size these offsets assume */
} LbBalanceTable;

""")
        for idx, (name, r, changed, ver) in enumerate(tables):
            key = name.lower()
            for j, (off, data) in enumerate(r):
                fh.write("static const uint8_t lb_%s_b%d[] = {%s};\n"
                         % (key, j, ",".join(str(b) for b in data)))
            fh.write("static const LbBalanceRun lb_%s_runs[] = {\n" % key)
            for j, (off, data) in enumerate(r):
                fh.write("    {%uu, %uu, lb_%s_b%d},\n" % (off, len(data), key, j))
            fh.write("};\n\n")

        fh.write("static const LbBalanceTable lb_balance_tables[] = {\n")
        for name, r, changed, ver in tables:
            fh.write("    {\"%s\", lb_%s_runs, %uu, %uu, %uu},\n"
                     % (DISPLAY.get(name, "%s %s" % (name, ver)), name.lower(), len(r), changed, len(base)))
        fh.write("};\n\n/* The number of presets: every pack bound derives from it. */\n"
                 "#define LB_BALANCE_PACK_COUNT %d\n\n#endif  // LB_BALANCE_DATA_H\n"
                 % len(tables))

    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
