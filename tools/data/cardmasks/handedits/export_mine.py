"""Export the final card masks for the port: cards/v10/lb_cardmasks.inc (C++ data).

Per card: blueprint index, internal name, CRC32 of the decoded stock 96x96 card as RGB555 (u16 LE per
pixel, row-major; transparent index-0 pixels written as 0x8000), the recolour anchors (L lo/hi of the
team part, chroma reference, chroma_keep, L_spread), flags, and the soft mask (alpha 0..255) RLE-coded
as (run, value) byte pairs, run 1..255, row-major over 96x96.
Usage: py -3.13 export_masks.py [vdir]   (default v10)"""
import os, sys, zlib, struct
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
VDIR = os.path.join(HERE, sys.argv[1] if len(sys.argv) > 1 else "v10")
sys.path.insert(0, VDIR)
import render, cardv3  # noqa: E402
sys.path.insert(0, os.path.join(HERE, "mine")); import edit as _edit  # hand edits on top of v10

FLAG_INDEX0_BLACK = 1      # mask covers index-0 (transparent, shows black) pixels: runtime must check the screen pixel is black
FLAG_DISABLED = 2          # card intentionally stock (no mask emitted)
FLAG_ENDSCREEN = 4         # victory/defeat art: 256x192 full top screen at (0,0), not a 96x96 card


def rgb555(card):
    I = card["I"]; P = card["P"]
    v = np.where(I >= 0, P[np.clip(I, 0, 255)] & 0x7FFF, 0x8000).astype("<u2")
    return v.tobytes()


def rle(alpha8):
    flat = alpha8.ravel().tolist(); out = bytearray(); i = 0
    while i < len(flat):
        v = flat[i]; n = 1
        while i + n < len(flat) and flat[i + n] == v and n < 255: n += 1
        out += bytes((n, v)); i += n
    return bytes(out)


def main():
    names = sorted(render.C, key=lambda n: (render.C[n]["bp"] if render.C[n]["bp"] >= 0 else 999, n))
    recs, blobs, total_rle = [], [], 0
    for n in names:
        R = render.compute(n); _m, _a, _ = _edit.apply(n, R); R = dict(R, mask=_m, alpha=_a); c = R["c"]; p = R["p"]
        crc = zlib.crc32(rgb555(c)) & 0xFFFFFFFF
        a8 = np.clip(np.floor(R["alpha"] * 255 + 0.5), 0, 255).astype(np.uint8)
        flags = 0
        if p.get("disabled") or not R["mask"].any():
            flags |= FLAG_DISABLED; a8[:] = 0
        if (R["mask"] & ~c["opaque"]).any(): flags |= FLAG_INDEX0_BLACK
        lab = cardv3.rgb2lab(c["rgb"].astype(float)); m = R["mask"]
        if m.any():
            Ls = lab[..., 0][m]; lo, hi = float(np.percentile(Ls, 2)), float(np.percentile(Ls, 98))
            if hi - lo < 8: lo, hi = lo - 4, hi + 4
            C = np.hypot(lab[..., 1], lab[..., 2]); cref = max(6.0, float(np.percentile(C[m], 90)))
        else:
            lo, hi, cref = 0.0, 100.0, 6.0
        blob = b"" if flags & FLAG_DISABLED else rle(a8)
        total_rle += len(blob)
        recs.append(dict(bp=c["bp"], name=n, crc=crc, lo=lo, hi=hi, cref=cref, keep=float(p.get("chroma_keep", 0.35)),
                         spread=float(p.get("L_spread", 0.18)), flags=flags, off=sum(len(b) for b in blobs), len=len(blob)))
        blobs.append(blob)
    # end-screen (victory / defeat) art: UI/Heroes/<name>, 256x192 at top-screen (0,0)
    import json as _json, endcards, endmask
    from PIL import Image as _Im
    EP = _json.load(open(os.path.join(VDIR, "endparams.json"), encoding="utf-8-sig"))
    for n in sorted(EP):
        c = endcards.load(n)
        crc = zlib.crc32((c["P"][c["I"]] & 0x7FFF).astype("<u2").tobytes()) & 0xFFFFFFFF
        a8 = np.asarray(_Im.open(os.path.join(VDIR, "endmasks", n + ".png")))
        m = a8 >= 128
        flags = FLAG_ENDSCREEN | (0 if m.any() else FLAG_DISABLED)
        lab = cardv3.rgb2lab(c["rgb"].astype(float))
        if m.any():
            Ls = lab[..., 0][m]; lo, hi = float(np.percentile(Ls, 2)), float(np.percentile(Ls, 98))
            if hi - lo < 8: lo, hi = lo - 4, hi + 4
            cref = max(6.0, float(np.percentile(np.hypot(lab[..., 1], lab[..., 2])[m], 90)))
        else:
            lo, hi, cref = 0.0, 100.0, 6.0
        blob = b"" if flags & FLAG_DISABLED else rle(a8)
        recs.append(dict(bp=-1, name="Heroes/" + n, crc=crc, lo=lo, hi=hi, cref=cref, keep=float(EP[n].get("chroma_keep", 0.35)),
                         spread=0.18, flags=flags, off=sum(len(b) for b in blobs), len=len(blob)))
        blobs.append(blob)
    data = b"".join(blobs)
    out = os.path.join(HERE, "mine", "lb_cardmasks.inc")
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by cards/export_masks.py from %s/params.json -- do not edit.\n" % os.path.basename(VDIR))
        f.write("// Team-colour masks for UI/GamePlayerCards (96x96, drawn at top-screen (24,40)). See RUNTIME.md.\n")
        f.write("// alpha RLE: (run 1..255, value 0..255) byte pairs, row-major 96x96.\n")
        f.write("enum { kCardMaskW = 96, kCardMaskH = 96, kEndMaskW = 256, kEndMaskH = 192, kCardFlagIndex0Black = 1, kCardFlagDisabled = 2, kCardFlagEndScreen = 4 };\n// Entries with kCardFlagEndScreen: name = \"Heroes/<file>\" (UI/Heroes/<file>.NCBR), mask is 256x192 at top-screen (0,0); bp = -1,\n// pick by name from the hero blueprint + victory flag (RUNTIME.md). CRC is over the 256x192 RGB555 image.\n")
        f.write("struct CardMask { int16_t bp; const char* name; uint32_t crc555; float L_lo, L_hi, C_ref, chroma_keep, L_spread;\n"
                "                  uint8_t flags; uint32_t rle_off, rle_len; };\n")
        z = zlib.compress(data, 9)
        f.write("// kCardMaskZ = zlib(concatenated RLE streams); inflate once to kCardMaskRleSize bytes, then index by rle_off.\n")
        f.write("enum { kCardMaskRleSize = %d };\n" % len(data))
        f.write("static const uint8_t kCardMaskZ[%d] = {\n" % len(z))
        for i in range(0, len(z), 32):
            f.write(",".join(str(b) for b in z[i:i + 32]) + ",\n")
        if not data: f.write("    0\n")
        f.write("};\n")
        f.write("static const CardMask kCardMasks[%d] = {\n" % len(recs))
        for r in recs:
            f.write('    {%d, "%s", 0x%08Xu, %.4ff, %.4ff, %.4ff, %.3ff, %.3ff, %d, %d, %d},\n' % (
                r["bp"], r["name"], r["crc"], r["lo"], r["hi"], r["cref"], r["keep"], r["spread"], r["flags"], r["off"], r["len"]))
        f.write("};\n")
    sz = os.path.getsize(out)
    print("cards", len(recs), "masked", sum(1 for r in recs if not r["flags"] & FLAG_DISABLED),
          "RLE bytes", len(data), "zlib bytes", len(zlib.compress(data, 9)), "file bytes", sz)


if __name__ == "__main__":
    main()
