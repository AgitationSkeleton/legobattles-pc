#!/usr/bin/env python3
"""Generate the Effect/ParticleSystem vtable table the port scans RAM for.

    python tools/lb_gen_fxvtables.py > port/runner/src/lb_fxvtables.h

Goal: effects and particles rendered in the widened columns. docs/210
answered the unit half by naming entities out of the entity pool; effects are
NOT in that pool. RTTI says why and where they are instead:

    Battles::Effect         -> Battles::DListItem
    Battles::ParticleSystem -> Battles::DListItem

They are linked-list items, not pool entries, so there is no array to index.
What there IS, for every one of them, is a vtable pointer in the object's first
word -- and out/eur/rtti.json already carries every vtable address the image
defines. Scanning main RAM for those words finds live effect objects directly,
with no need to locate a list head first.

This is generated rather than written by hand because the addresses are data
from the ROM, and the project never hand-edits generated output. Re-run it if
the RTTI extract is ever regenerated.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RTTI = os.path.join(ROOT, "out", "eur", "rtti.json")


def addr_of(t):
    a = t["address"]
    return int(a, 16) if isinstance(a, str) else int(a)


def main():
    d = json.load(open(RTTI))
    infos = d["typeinfos"]
    by_addr = {addr_of(t): t for t in infos}

    def derives_from(t, wanted):
        seen = set()
        while t is not None:
            if t["name"] == wanted:
                return True
            bases = t.get("bases") or []
            if not bases:
                return False
            b = bases[0]["typeinfo"]
            if b in seen or b not in by_addr:
                return False
            seen.add(b)
            t = by_addr[b]
        return False

    rows = []
    for t in infos:
        name = t["name"]
        # Battles::Effect itself is abstract, but include it: an object whose
        # vtable is the base's is still an effect, and excluding it would make
        # a zero result ambiguous.
        if not (derives_from(t, "Battles::Effect")
                or name == "Battles::ParticleSystem"):
            continue
        for vt in t.get("vtables") or []:
            rows.append((int(vt["vtable"]), name))
    rows.sort()

    out = sys.stdout
    out.write("// GENERATED by tools/lb_gen_fxvtables.py -- do not edit.\n")
    out.write("//\n")
    out.write("// Vtable addresses of every Battles::Effect subclass and of\n")
    out.write("// Battles::ParticleSystem. An object in main RAM whose first\n")
    out.write("// word is one of these IS one of them; that is what lets the\n")
    out.write("// port audit effects the way docs/210 audited units.\n")
    out.write("#ifndef LB_FXVTABLES_H\n#define LB_FXVTABLES_H\n\n")
    out.write("#include <stdint.h>\n\n")
    out.write("typedef struct { uint32_t vtable; const char* name; } LbFxClass;\n\n")
    out.write("static const LbFxClass g_lb_fx_classes[] = {\n")
    for a, n in rows:
        short = n.replace("Battles::", "")
        out.write("    {0x%08Xu, \"%s\"},\n" % (a, short))
    out.write("};\n\n")
    out.write("enum { kLbFxClassCount = %d };\n\n" % len(rows))
    out.write("#endif\n")
    sys.stderr.write("%d vtables across %d classes\n"
                     % (len(rows), len({n for _, n in rows})))


if __name__ == "__main__":
    main()
