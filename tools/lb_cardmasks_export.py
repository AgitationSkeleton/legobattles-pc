#!/usr/bin/env python3
"""Regenerate port/runner/src/lb_cardmasks.inc: the team-colour masks of the top screen's unit
cards (UI/GamePlayerCards, 96x96 at (24,40)) and of the victory/defeat pictures (UI/Heroes,
256x192 at (0,0)). docs/486.

Inputs (no cartridge art is stored): the extracted ROM under out/eur/nitrofs (LB_NITROFS to
override) and the hand-authored parameters in tools/data/cardmasks/ (params.json: per-card
regions; team_hues.json: each card's stock team hue; endparams.json: the end pictures).
Decoded art and review images go to out/cardmasks/ (LB_CARDMASKS_OUT), which is not tracked.

Per entry: blueprint (-1/-2/-3 for Bridge, K_Unknown, A_LaserTrooper; -1 for end pictures),
name, CRC32 of the stock picture as RGB555 (u16 LE per pixel; transparent index-0 card pixels
as 0x8000), the recolour anchors (L lo/hi and C reference of the team part, chroma_keep,
L_spread), flags, and the soft mask (alpha 0..255) as (run 1..255, value) byte pairs,
row-major. All masks are concatenated and zlib-compressed into kCardMaskZ.

Usage: py -3.13 tools/lb_cardmasks_export.py [out.inc]
(numpy, scipy and Pillow are needed: the Windows py -3.13, not the MSYS python.)"""
import os
import sys
import zlib
import json

TOOLS = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(TOOLS)
DATA = os.path.join(TOOLS, "data", "cardmasks")
sys.path.insert(0, DATA)

import numpy as np  # noqa: E402
import render, cardv3, endcards, endmask  # noqa: E402

FLAG_INDEX0_BLACK = 1   # the mask covers index-0 (transparent, shows black) pixels
FLAG_DISABLED = 2       # intentionally stock: no mask
FLAG_ENDSCREEN = 4      # a 256x192 victory/defeat picture at top-screen (0,0)


def rgb555(card):
    I = card["I"]; P = card["P"]
    return np.where(I >= 0, P[np.clip(I, 0, 255)] & 0x7FFF, 0x8000).astype("<u2").tobytes()


def rle(alpha8):
    flat = alpha8.ravel().tolist(); out = bytearray(); i = 0
    while i < len(flat):
        v = flat[i]; n = 1
        while i + n < len(flat) and flat[i + n] == v and n < 255: n += 1
        out += bytes((n, v)); i += n
    return bytes(out)


def anchors(rgb, m):
    lab = cardv3.rgb2lab(rgb.astype(float))
    if not m.any():
        return 0.0, 100.0, 6.0
    Ls = lab[..., 0][m]
    lo, hi = float(np.percentile(Ls, 2)), float(np.percentile(Ls, 98))
    if hi - lo < 8: lo, hi = lo - 4, hi + 4
    cref = max(6.0, float(np.percentile(np.hypot(lab[..., 1], lab[..., 2])[m], 90)))
    return lo, hi, cref


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "port", "runner", "src", "lb_cardmasks.inc")
    names = sorted(render.C, key=lambda n: (render.C[n]["bp"] if render.C[n]["bp"] >= 0 else 999, n))
    recs, blobs = [], []
    for n in names:
        R = render.compute(n); c = R["c"]; p = R["p"]
        crc = zlib.crc32(rgb555(c)) & 0xFFFFFFFF
        a8 = np.clip(np.floor(R["alpha"] * 255 + 0.5), 0, 255).astype(np.uint8)
        flags = 0
        if p.get("disabled") or not R["mask"].any():
            flags |= FLAG_DISABLED; a8[:] = 0
        if (R["mask"] & ~c["opaque"]).any(): flags |= FLAG_INDEX0_BLACK
        lo, hi, cref = anchors(c["rgb"], R["mask"])
        blob = b"" if flags & FLAG_DISABLED else rle(a8)
        recs.append(dict(bp=c["bp"], name=n, crc=crc, lo=lo, hi=hi, cref=cref, keep=float(p.get("chroma_keep", 0.35)),
                         spread=float(p.get("L_spread", 0.18)), flags=flags, off=sum(len(b) for b in blobs), len=len(blob)))
        blobs.append(blob)
    EP = json.load(open(os.path.join(DATA, "endparams.json"), encoding="utf-8-sig"))
    for n in sorted(EP):
        c, m, a = endmask.compute(n, EP[n])
        crc = zlib.crc32((c["P"][c["I"]] & 0x7FFF).astype("<u2").tobytes()) & 0xFFFFFFFF
        a8 = (a * 255 + 0.5).astype(np.uint8)
        m = a8 >= 128
        flags = FLAG_ENDSCREEN | (0 if m.any() else FLAG_DISABLED)
        lo, hi, cref = anchors(c["rgb"], m)
        blob = b"" if flags & FLAG_DISABLED else rle(a8)
        recs.append(dict(bp=-1, name="Heroes/" + n, crc=crc, lo=lo, hi=hi, cref=cref, keep=float(EP[n].get("chroma_keep", 0.35)),
                         spread=0.18, flags=flags, off=sum(len(b) for b in blobs), len=len(blob)))
        blobs.append(blob)
    data = b"".join(blobs)
    z = zlib.compress(data, 9)
    with open(out, "w", newline="") as f:
        w = f.write
        w("// Generated by tools/lb_cardmasks_export.py from tools/data/cardmasks -- do not edit. docs/486.\n")
        w("// Team-colour masks: UI/GamePlayerCards (96x96 at top-screen (24,40)) and UI/Heroes victory/defeat\n")
        w("// pictures (256x192 at (0,0), kCardFlagEndScreen, name \"Heroes/<file>\"). Mask: (run 1..255, alpha) byte\n")
        w("// pairs, row-major; all concatenated, zlib-compressed into kCardMaskZ (inflate once).\n")
        w("enum { kCardMaskW = 96, kCardMaskH = 96, kEndMaskW = 256, kEndMaskH = 192,\n")
        w("       kCardFlagIndex0Black = 1, kCardFlagDisabled = 2, kCardFlagEndScreen = 4 };\n")
        w("struct CardMask { int16_t bp; const char* name; uint32_t crc555; float L_lo, L_hi, C_ref, chroma_keep, L_spread;\n")
        w("                  uint8_t flags; uint32_t rle_off, rle_len; };\n")
        w("enum { kCardMaskRleSize = %d };\n" % len(data))
        w("static const uint8_t kCardMaskZ[%d] = {\n" % len(z))
        for i in range(0, len(z), 32):
            w(",".join(str(b) for b in z[i:i + 32]) + ",\n")
        w("};\n")
        w("static const CardMask kCardMasks[%d] = {\n" % len(recs))
        for r in recs:
            w('    {%d, "%s", 0x%08Xu, %.4ff, %.4ff, %.4ff, %.3ff, %.3ff, %d, %d, %d},\n' % (
                r["bp"], r["name"], r["crc"], r["lo"], r["hi"], r["cref"], r["keep"], r["spread"], r["flags"], r["off"], r["len"]))
        w("};\n")
    print("entries", len(recs), "masked", sum(1 for r in recs if not r["flags"] & FLAG_DISABLED),
          "RLE bytes", len(data), "zlib bytes", len(z), "file bytes", os.path.getsize(out))


if __name__ == "__main__":
    main()
