#!/usr/bin/env python3
"""Generate the bundled FactionWars level-palette table for the port (docs/387).

FactionWars recolours the three tileset palettes -- KingTileset.NCLR,
PirateTileset.NCLR and MarsTileset.NCLR, each 256 BGR555 colours at +0x28 of an
uncompressed RLCN file (docs/101, docs/387). REbalance ships the same three
palettes byte for byte and FUNLite ships vanilla's, so FactionWars is the only
other palette set there is.

**What is bundled is a list of (index, colour) pairs, not anyone's ROM.** Only
the colours FactionWars changes are emitted; the vanilla colours are read from
the player's own ROM at run time. Run this, do not hand-edit the output.

    python tools/lb_genpalette.py --out port/runner/src/lb_palette_data.h
"""

from __future__ import annotations

import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nds_extract

# LB_MODS_DIR, else roms/lbmods two levels above this checkout.
MODS_DIR = os.environ.get("LB_MODS_DIR") or os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "roms", "lbmods")
BASE = "VANILLA_MapBase.nds"
MOD = "FactionWars_MapBase.nds"
# World order matches FUN_020A44C0: 0 King, 1 Pirate, 2 Mars.
WORLDS = [("King", "KingTileset.NCLR"), ("Pirate", "PirateTileset.NCLR"),
          ("Mars", "MarsTileset.NCLR")]
COLOURS_AT = 0x28


def file_from_rom(raw, target):
    fnt_off, fnt_len = struct.unpack("<II", raw[0x40:0x48])
    fat_off, fat_len = struct.unpack("<II", raw[0x48:0x50])
    paths, _dirs = nds_extract.parse_fnt(raw[fnt_off:fnt_off + fnt_len])
    fat = nds_extract.parse_fat(raw[fat_off:fat_off + fat_len])
    for fid, name in paths.items():
        if name.replace("\\", "/").lstrip("/") == target and fid < len(fat):
            start, end = fat[fid]
            return raw[start:end]
    raise SystemExit("no %s" % target)


def colours(nclr):
    if nclr[:4] != b"RLCN":
        raise SystemExit("not an uncompressed NCLR")
    return list(struct.unpack_from("<256H", nclr, COLOURS_AT))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="port/runner/src/lb_palette_data.h")
    ap.add_argument("--mods-dir", default=MODS_DIR)
    args = ap.parse_args()
    base = open(os.path.join(args.mods_dir, BASE), "rb").read()
    mod = open(os.path.join(args.mods_dir, MOD), "rb").read()
    tables = []
    for world, path in WORLDS:
        v = colours(file_from_rom(base, path))
        f = colours(file_from_rom(mod, path))
        pairs = [(i, f[i]) for i in range(256) if f[i] != v[i]]
        tables.append((world, path, pairs))
        print("%s: %d colours differ" % (path, len(pairs)))

    with open(args.out, "w", newline="\n") as fh:
        fh.write("""// lb_palette_data.h - the FactionWars level palettes, as differences.
//
// GENERATED by tools/lb_genpalette.py. Do not hand-edit; re-run the generator.
//
// The colours FactionWars changes in the three tileset palettes, as
// (index, BGR555) pairs against the retail files. The vanilla colours are read
// from the player's own ROM; nothing of the ROM is here (docs/387).
//
// CREDIT. FactionWars is a community romhack of LEGO Battles, not this
// project's work; REbalance (Ryncat et al., docs/101) ships the same palettes.

#ifndef LB_PALETTE_DATA_H
#define LB_PALETTE_DATA_H

#include <stdint.h>

typedef struct LbPaletteDelta {
    uint8_t index;
    uint16_t colour;
} LbPaletteDelta;

typedef struct LbPaletteTable {
    const char* nclr;            /* the NitroFS path of the vanilla file */
    const LbPaletteDelta* deltas;
    uint32_t count;
} LbPaletteTable;

""")
        for world, path, pairs in tables:
            fh.write("static const LbPaletteDelta lb_fw_%s[] = {\n" % world.lower())
            for k in range(0, len(pairs), 6):
                fh.write("    " + " ".join("{%u, 0x%04Xu}," % p
                                           for p in pairs[k:k + 6]) + "\n")
            fh.write("};\n\n")
        fh.write("/* World order: FUN_020A44C0's, 0 King, 1 Pirate, 2 Mars. */\n")
        fh.write("static const LbPaletteTable lb_fw_palettes[3] = {\n")
        for world, path, pairs in tables:
            fh.write("    {\"%s\", lb_fw_%s, %uu},\n" % (path, world.lower(), len(pairs)))
        fh.write("};\n\n#endif  // LB_PALETTE_DATA_H\n")
    print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
