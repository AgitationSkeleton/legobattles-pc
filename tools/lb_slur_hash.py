"""Hash a slur-stem list for the servers and the game (docs/502).

    py -3.13 -I tools/lb_slur_hash.py <stems.txt>

The list never enters the repository; delete it afterwards. One stem per line
(# comments and blank lines are skipped); "allow <word>" lines name ordinary
words that contain a stem, removed from a text before matching (hashed too).
Each stem is folded exactly as the matcher folds text before it is hashed. Writes the hashes into:
  services/master-server/master_server.py  (between the SLUR HASHES markers)
  services/master-server-cloudflare/src/slur_words.js
  port/runner/src/lb_slur_words.h
and prints only how many stems there were -- never a stem.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "services", "master-server"))
import master_server as ms  # noqa: E402


def fold_table():
    """Look-alike letters by their Unicode names: every LATIN letter whose
    name ends in a plain letter (small capitals, dotless, turned, script...),
    to that letter. Written into both servers' tables, so they agree whatever
    Unicode version their Python or JavaScript has."""
    import unicodedata
    rx = re.compile(r"^LATIN (?:SMALL |CAPITAL )?LETTER (?:SMALL CAPITAL |TURNED |REVERSED |INVERTED |"
                    r"DOTLESS |SCRIPT |CLOSED |OPEN |SIDEWAYS |BARRED |STRETCHED |LONG |SHORT |"
                    r"MIDDLE-WELSH |INSULAR |BROKEN |SMALL )*([A-Z])(?: WITH .*)?$")
    ranges = [(0x00C0, 0x0530), (0x1D00, 0x1DC0), (0x1E00, 0x2000), (0x2C60, 0x2C80),
              (0xA720, 0xA800), (0xAB30, 0xAB70)]
    out = {}
    for lo, hi in ranges:
        for cp in range(lo, hi):
            ch = chr(cp)
            m = rx.match(unicodedata.name(ch, ""))
            if not m:
                continue
            low = ch.lower()
            plain = "".join(c for c in unicodedata.normalize("NFKD", low)
                            if not unicodedata.category(c).startswith("M"))
            if plain.isascii() and plain.isalpha():
                continue   # NFKD folds it already
            out[low] = m.group(1).lower()
    # Letters whose names do not say (alpha, iota, upsilon-like) and the rest
    # of the Cyrillic and Greek look-alikes.
    out.update({"ɑ": "a", "ɩ": "i", "ʋ": "v", "ɛ": "e", "ɔ": "o", "ʊ": "u", "ɢ": "g", "ʜ": "h",
                "ј": "j", "ԛ": "q", "ԝ": "w", "һ": "h", "ѡ": "w", "ѵ": "v", "ү": "y", "ҡ": "k",
                "ϳ": "j", "ϲ": "c", "ϱ": "p", "ϰ": "k", "ɴ": "n", "ʀ": "r", "ʟ": "l", "ʏ": "y"})
    return dict(sorted(out.items()))


def write_fold():
    table = fold_table()
    py = os.path.join(ROOT, "services", "master-server", "master_server.py")
    s = open(py, encoding="utf-8", newline="").read()
    nl = "\r\n" if "\r\n" in s else "\n"
    items = ["    %r: %r," % (k, v) for k, v in table.items()]
    body = nl.join(["# BEGIN SLUR FOLD (tools/lb_slur_hash.py --fold)", "SLUR_FOLD_EXTRA = {"]
                   + items + ["}", "# END SLUR FOLD"])
    s2, n = re.subn(r"# BEGIN SLUR FOLD.*?# END SLUR FOLD", lambda m: body, s, flags=re.S)
    assert n == 1
    open(py, "w", encoding="utf-8", newline="").write(s2)
    js = os.path.join(ROOT, "services", "master-server-cloudflare", "src", "slur_fold.js")
    with open(js, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/lb_slur_hash.py --fold (docs/502): look-alike letters\n"
                "// to the letters they stand for, by their Unicode names.\n")
        f.write("export const SLUR_FOLD_EXTRA = " + json.dumps(table, ensure_ascii=False, indent=0) + ";\n")
    print("%d look-alike letters" % len(table))


def main():
    if sys.argv[1] == "--fold":
        return write_fold()
    stems, allow = set(), set()
    ms.SLUR_ALLOW_HASHES = frozenset()   # stems are keyed without any old allow list
    for ln in open(sys.argv[1], encoding="utf-8"):
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        if ln.startswith("allow "):
            allow.add(ms._slur_fold(ln[6:]))
            continue
        k = ms.slur_keys(ln)[0]
        if len(k) >= 3:
            stems.add(k)
    alo = min((len(k) for k in allow), default=0)
    ahi = max((len(k) for k in allow), default=0)
    ahashes = sorted(ms.slur_hash(k) for k in allow)
    if not stems:
        sys.exit("no stems")
    lo = min(len(k) for k in stems)
    hi = max(len(k) for k in stems)
    hashes = sorted(ms.slur_hash(k) for k in stems)

    py = os.path.join(ROOT, "services", "master-server", "master_server.py")
    s = open(py, encoding="utf-8", newline="").read()
    nl = "\r\n" if "\r\n" in s else "\n"
    body = (nl.join(["# BEGIN SLUR HASHES (tools/lb_slur_hash.py)",
                     "SLUR_MIN, SLUR_MAX = %d, %d" % (lo, hi),
                     "SLUR_HASHES = frozenset(("]
                    + ["    0x%016X," % h for h in hashes]
                    + ["))", "SLUR_ALLOW_MIN, SLUR_ALLOW_MAX = %d, %d" % (alo, ahi),
                       "SLUR_ALLOW_HASHES = frozenset(("]
                    + ["    0x%016X," % h for h in ahashes]
                    + ["))", "# END SLUR HASHES"]))
    s2, n = re.subn(r"# BEGIN SLUR HASHES.*?# END SLUR HASHES", lambda m: body, s, flags=re.S)
    assert n == 1
    open(py, "w", encoding="utf-8", newline="").write(s2)

    js = os.path.join(ROOT, "services", "master-server-cloudflare", "src", "slur_words.js")
    with open(js, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/lb_slur_hash.py (docs/502): salted FNV-1a 64 hashes of\n"
                "// slur stems, folded as src/slur.js folds text. No stem is in this file.\n"
                "export const SLUR_MIN = %d, SLUR_MAX = %d;\n" % (lo, hi))
        f.write("export const SLUR_HASHES = new Set([\n")
        for h in hashes:
            f.write("  0x%016Xn,\n" % h)
        f.write("]);\n")
        f.write("export const SLUR_ALLOW_MIN = %d, SLUR_ALLOW_MAX = %d;\n" % (alo, ahi))
        f.write("export const SLUR_ALLOW_HASHES = new Set([\n")
        for h in ahashes:
            f.write("  0x%016Xn,\n" % h)
        f.write("]);\n")

    hp = os.path.join(ROOT, "port", "runner", "src", "lb_slur_words.h")
    with open(hp, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/lb_slur_hash.py (docs/502): salted FNV-1a 64 hashes of\n"
                "// slur stems, folded as lb_chat.cpp folds a name. No stem is in this file.\n"
                "#pragma once\n#include <cstdint>\n"
                "constexpr int kSlurMin = %d, kSlurMax = %d;\n" % (lo, hi))
        f.write("const uint64_t kSlurHashes[] = {\n")
        for h in hashes:
            f.write("    0x%016XULL,\n" % h)
        f.write("};\n")
        f.write("constexpr int kSlurAllowMin = %d, kSlurAllowMax = %d;\n" % (alo, ahi))
        f.write("const uint64_t kSlurAllowHashes[] = {\n")
        for h in ahashes:
            f.write("    0x%016XULL,\n" % h)
        f.write("};\n")
    print("%d stems hashed (lengths %d-%d)" % (len(stems), lo, hi))


if __name__ == "__main__":
    main()
