"""Hash a swear list into port/runner/src/lb_chat_words.h (docs/415). The list
never enters the repository; only salted FNV-1a hashes do. Each line of the
list is "root <word>" (matched inside words) or "word <word>" (whole words).

    py -3.13 -I tools/lb_swear_hash.py <list.txt> port/runner/src/lb_chat_words.h
"""
import sys

SALT = b"lbziff1:"


def h64(word):
    h = 0xCBF29CE484222325
    for c in SALT + word.encode("ascii"):
        h ^= c
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    roots, words = set(), set()
    lo, hi = 99, 0
    for ln in open(sys.argv[1], encoding="ascii"):
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        kind, w = ln.split()
        w = w.lower()
        (roots if kind == "root" else words).add(h64(w))
        if kind == "root":
            lo, hi = min(lo, len(w)), max(hi, len(w))
    out = ["// Generated by tools/lb_swear_hash.py (docs/415) from a word list that is not",
           "// in this repository. Salted FNV-1a 64 (lb_chat.cpp, word_hash), sorted.",
           "#pragma once",
           "#include <cstdint>",
           "constexpr int kSwearRootMin = %d, kSwearRootMax = %d;" % (lo, hi),
           "const uint64_t kSwearRoots[] = {"]
    out += ["    0x%016XULL," % v for v in sorted(roots)]
    out += ["};", "const uint64_t kSwearWords[] = {"]
    out += ["    0x%016XULL," % v for v in sorted(words)]
    out += ["};", ""]
    open(sys.argv[2], "w", newline="\n").write("\n".join(out))
    print("%d roots (%d..%d letters), %d words" % (len(roots), lo, hi, len(words)))


main()
