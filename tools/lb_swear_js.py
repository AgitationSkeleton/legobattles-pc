"""Copy the swear filter's hashes (port/runner/src/lb_chat_words.h, docs/415) into
the master server's src/swear_words.js, so the score tables (SG-0018) refuse the
names the game's own filter would change. Hashes only: no word is in either file.

    py -3.13 -I tools/lb_swear_js.py
"""
import os
import re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "port", "runner", "src", "lb_chat_words.h")
DST = os.path.join(HERE, "services", "master-server-cloudflare", "src", "swear_words.js")


def main():
    text = open(SRC, encoding="ascii").read()
    lo, hi = map(int, re.search(r"kSwearRootMin = (\d+), kSwearRootMax = (\d+)", text).groups())

    def table(name):
        body = re.search(name + r"\[\] = \{(.*?)\};", text, re.S).group(1)
        return re.findall(r"0x([0-9A-Fa-f]{16})ULL", body)

    out = ["// Generated by tools/lb_swear_js.py from port/runner/src/lb_chat_words.h",
           "// (docs/415): salted FNV-1a 64 hashes of the game's swear filter. No word",
           "// is in this file. src/swear.js uses them.",
           "export const ROOT_MIN = %d, ROOT_MAX = %d;" % (lo, hi)]
    for js, c in (("ROOTS", "kSwearRoots"), ("WORDS", "kSwearWords")):
        out.append("export const %s = new Set([" % js)
        out += ["  0x%sn," % h.upper() for h in table(c)]
        out.append("]);")
    with open(DST, "w", encoding="ascii", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    print("wrote", DST)


if __name__ == "__main__":
    main()
