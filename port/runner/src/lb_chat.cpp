// ---- the filter ------------------------------------------------------------

uint64_t word_hash(const char* s, size_t n) {
    uint64_t h = 0xCBF29CE484222325ull;
    for (const char* p = "lbziff1:"; *p; ++p) {
        h ^= (unsigned char)*p;
        h *= 0x100000001B3ull;
    }
    for (size_t i = 0; i < n; ++i) {
        h ^= (unsigned char)s[i];
        h *= 0x100000001B3ull;
    }
    return h;
}

template <size_t N>
bool in_set(const uint64_t (&set)[N], uint64_t h) {
    return std::binary_search(set, set + N, h);
}

// LB_SWEAR_TEST_WORDS=a,b,c adds whole words for a test (an innocent name can
// then stand in for a swear word). Test aid only.
std::vector<std::string>& test_words() {
    static std::vector<std::string> w;
    static bool done = false;
    if (!done) {
        done = true;
        if (const char* p = std::getenv("LB_SWEAR_TEST_WORDS")) {
            std::string cur;
            for (;; ++p) {
                if (*p == ',' || !*p) {
                    if (!cur.empty()) w.push_back(cur);
                    cur.clear();
                    if (!*p) break;
                } else {
                    cur += (char)std::tolower((unsigned char)*p);
                }
            }
        }
    }
    return w;
}

bool is_word(const std::string& t) {
    if (t.empty()) return false;
    const uint64_t h = word_hash(t.data(), t.size());
    if (in_set(kSwearWords, h) || in_set(kSwearRoots, h)) return true;
    for (const std::string& w : test_words())
        if (w == t) return true;
    return false;
}

// A letter for matching, or 0 for a character that separates words.
char letter(char c) {
    if (c >= 'a' && c <= 'z') return c;
    if (c >= 'A' && c <= 'Z') return (char)(c - 'A' + 'a');
    switch (c) {
        case '4': case '@': return 'a';
        case '3': return 'e';
        case '1': case '!': return 'i';
        case '0': return 'o';
        case '5': case '$': return 's';
        case '7': case '+': return 't';
        default: return 0;
    }
}

std::string collapse(const std::string& t) {
    std::string o;
    for (char c : t)
        if (o.empty() || o.back() != c) o += c;
    return o;
}

bool ends_with(const std::string& s, const char* tail) {
    const size_t n = std::strlen(tail);
    return s.size() >= n && s.compare(s.size() - n, n, tail) == 0;
}

// The whole word, or the word without an ending, is listed.
bool whole_word(const std::string& t) {
    static const char* const kEndings[] = {"ing", "in", "ers", "er", "ed",
                                           "es", "s", "y", "ies"};
    for (const std::string& v : {t, collapse(t)}) {
        if (is_word(v)) return true;
        for (const char* e : kEndings)
            if (ends_with(v, e) && v.size() > std::strlen(e) + 1 &&
                is_word(v.substr(0, v.size() - std::strlen(e))))
                return true;
    }
    return false;
}

// "ziff" or "ziffing", in the case of `orig`.
std::string replacement(const std::string& orig, bool ing) {
    int upper = 0, lower = 0;
    for (char c : orig) {
        if (c >= 'A' && c <= 'Z') ++upper;
        else if (c >= 'a' && c <= 'z') ++lower;
    }
    std::string r = ing ? "ziffing" : "ziff";
    if (upper >= 2 && lower == 0) {
        for (char& c : r) c = (char)(c - 'a' + 'A');
    } else if (!orig.empty() && orig[0] >= 'A' && orig[0] <= 'Z') {
        r[0] = 'Z';
    }
    return r;
}

std::string filter(const std::string& in) {
    const size_t n = in.size();
    std::string norm(n, '\0');
    for (size_t i = 0; i < n; ++i) norm[i] = letter(in[i]);
    std::vector<std::pair<size_t, size_t>> spans;   // [begin, end)
    size_t i = 0;
    while (i < n) {
        if (!norm[i]) { ++i; continue; }
        size_t j = i;
        while (j < n && norm[j]) ++j;
        const std::string tok = norm.substr(i, j - i);
        if (whole_word(tok)) {
            spans.push_back({i, j});
        } else {
            for (size_t s = i; s < j; ++s) {
                for (int len = kSwearRootMax; len >= kSwearRootMin; --len) {
                    if (s + (size_t)len > j) continue;
                    if (!in_set(kSwearRoots, word_hash(norm.data() + s, (size_t)len)))
                        continue;
                    size_t e = s + (size_t)len;
                    // An ending straight after it belongs to the match: the
                    // longest of these that runs to the end of the word, else
                    // "-ing" inside a longer word.
                    static const char* const kTails[] = {"ers", "ing", "in", "er",
                                                         "ed", "es", "s", "y"};
                    bool tail = false;
                    for (const char* t : kTails) {
                        const size_t tl = std::strlen(t);
                        if (e + tl == j && norm.compare(e, tl, t) == 0) {
                            e += tl;
                            tail = true;
                            break;
                        }
                    }
                    if (!tail && e + 3 <= j && norm.compare(e, 3, "ing") == 0) e += 3;
                    spans.push_back({s, e});
                    s = e - 1;
                    break;
                }
            }
        }
        i = j;
    }
    if (spans.empty()) return in;
    std::string out;
    size_t at = 0;
    for (const auto& sp : spans) {
        out.append(in, at, sp.first - at);
        const std::string orig = in.substr(sp.first, sp.second - sp.first);
        out += replacement(orig, ends_with(norm.substr(sp.first, sp.second - sp.first),
                                           "ing"));
        at = sp.second;
    }
    out.append(in, at, std::string::npos);
    return out;
}

// What a player sees: filtered while the setting is on.
std::string shown(const std::string& s) {
    return lb_setting_swear_filter() ? filter(s) : s;
}

// ---- the chat --------------------------------------------------------------

struct Msg {
    std::string name, text;
    int hero = -1;
    bool mine = false;
    unsigned long long at = 0;   // SDL ticks
};

std::mutex g_mu;
std::deque<Msg> g_log;                              // newest last
std::deque<std::vector<uint8_t>> g_outbox;          // datagrams to send
std::deque<std::pair<uint32_t, uint32_t>> g_seen;   // (origin, seq)
uint32_t g_origin = 0, g_seq = 0;
bool g_open = false, g_focus = false;
char g_line[160] = "";

constexpr size_t kLogMax = 100, kSeenMax = 256, kTextMax = 150, kNameMax = 31;

// In an online lobby or match: a host's lobby open (2), starting (3, 4) or
// playing (11); a joiner joined (5) or playing (12). Not the setup screens or
// the Join list's search, where nobody would receive a message.
bool online() {
    const int s = lb_net_guest_state();
    return s == 2 || s == 3 || s == 4 || s == 11 || s == 5 || s == 12;
}
bool hosting() {
    const int s = lb_net_guest_state();
    return s == 2 || s == 3 || s == 4 || s == 11;
}

uint32_t origin() {
    if (!g_origin) {
        const uint64_t t = SDL_GetPerformanceCounter();
        g_origin = (uint32_t)(t ^ (t >> 32) ^ 0x9E3779B9u ^ (uintptr_t)&g_origin);
        if (!g_origin) g_origin = 1;
    }
    return g_origin;
}

bool seen(uint32_t o, uint32_t s) {   // under g_mu
    for (const auto& p : g_seen)
        if (p.first == o && p.second == s) return true;
    g_seen.push_back({o, s});
    if (g_seen.size() > kSeenMax) g_seen.pop_front();
    return false;
}

void put_le32(std::vector<uint8_t>* v, uint32_t x) {
    for (int b = 0; b < 4; ++b) v->push_back((uint8_t)(x >> (8 * b)));
}

std::vector<uint8_t> encode(uint32_t o, uint32_t s, int hero, const std::string& name,
                            const std::string& text) {
    std::vector<uint8_t> d = {'L', 'B', 'C', '1'};
    put_le32(&d, o);
    put_le32(&d, s);
    const uint16_t h = hero >= 0 ? (uint16_t)hero : 0xFFFFu;
    d.push_back((uint8_t)(h & 0xFF));
    d.push_back((uint8_t)(h >> 8));
    const size_t nl = std::min(name.size(), kNameMax);
    d.push_back((uint8_t)nl);
    d.insert(d.end(), name.begin(), name.begin() + (long)nl);
    const size_t tl = std::min(text.size(), kTextMax);
    d.push_back((uint8_t)tl);
    d.insert(d.end(), text.begin(), text.begin() + (long)tl);
    return d;
}

void add(Msg m) {   // under g_mu
    g_log.push_back(std::move(m));
    if (g_log.size() > kLogMax) g_log.pop_front();
}

void log_line(const char* how, const Msg& m) {
    // The log gets what a filtered screen would show: logs are shared.
    std::fprintf(stderr, "[lb_chat] %s %s (hero %d): %s\n", how,
                 filter(m.name).c_str(), m.hero, filter(m.text).c_str());
    std::fflush(stderr);
}

void send(const std::string& text) {
    if (text.empty()) return;
    Msg m;
    m.name = lb_overlay_player_name();
    m.text = text.substr(0, kTextMax);
    m.hero = lb_net_local_hero();
    m.mine = true;
    m.at = SDL_GetTicks64();
    std::lock_guard<std::mutex> lk(g_mu);
    const uint32_t s = ++g_seq;
    seen(origin(), s);
    g_outbox.push_back(encode(origin(), s, m.hero, m.name, m.text));
    log_line("sent", m);
    add(std::move(m));
}

// The hero's battle-HUD icon, `size` px, or nothing.
void hero_icon(SDL_Renderer* r, int hero, float size) {
    if (hero < 0) return;
    SDL_Texture* hud = lb_teams_hud_atlas(r);
    float u0, v0, u1, v1;
    if (!hud || !lb_teams_hud_icon_uv(hero, &u0, &v0, &u1, &v1)) return;
    ImGui::Image((ImTextureID)(intptr_t)hud, ImVec2(size, size), ImVec2(u0, v0),
                 ImVec2(u1, v1));
    ImGui::SameLine();
}

void message_line(SDL_Renderer* r, const Msg& m, float icon, float width) {
    ImGui::PushTextWrapPos(ImGui::GetCursorPosX() + width);
    hero_icon(r, m.hero, icon);
    const ImVec4 col = m.mine ? ImVec4(0.65f, 0.85f, 1.0f, 1.0f)
                              : ImVec4(1.0f, 0.85f, 0.35f, 1.0f);
    ImGui::TextColored(col, "%s:", shown(m.name).c_str());
    ImGui::SameLine();
    ImGui::TextUnformatted(shown(m.text).c_str());
    ImGui::PopTextWrapPos();
}

// LB_CHAT_TEST_SEND=<text> sends once, LB_CHAT_TEST_DELAY seconds (5) after
// this machine is first online. Test aid only.
// LB_CHAT_TEST_TYPE=<text> types a message as a player would: five seconds
// after this machine is online, a T key event, then (lb_chat_open) the text
// as text events, then Return. Everything goes through SDL's own queue, the
// overlay's key handling and the chat box. Test aid only.
// The game window's id: ImGui's SDL2 backend drops an event for a window it
// does not know, and keeps the id as the main viewport's handle.
Uint32 window_id() {
    return (Uint32)(intptr_t)ImGui::GetMainViewport()->PlatformHandle;
}
void push_key(SDL_Scancode sc, SDL_Keycode sym) {
    for (int down = 1; down >= 0; --down) {
        SDL_Event e{};
        e.type = down ? SDL_KEYDOWN : SDL_KEYUP;
        e.key.windowID = window_id();
        e.key.state = down ? SDL_PRESSED : SDL_RELEASED;
        e.key.keysym.scancode = sc;
        e.key.keysym.sym = sym;
        SDL_PushEvent(&e);
    }
}
void push_text(const std::string& all) {
    for (size_t i = 0; i < all.size(); i += 8) {
        SDL_Event e{};
        e.type = SDL_TEXTINPUT;
        e.text.windowID = window_id();
        std::snprintf(e.text.text, sizeof e.text.text, "%s", all.substr(i, 8).c_str());
        SDL_PushEvent(&e);
    }
}
// The steps: T five seconds after this machine is online; the text half a
// second after the box opened (once its field has the keyboard); Return a
// second after that.
void test_type_tick() {
    static const char* text = std::getenv("LB_CHAT_TEST_TYPE");
    static unsigned long long since = 0, opened = 0;
    static int step = 0;
    if (!text || !*text || step >= 3 || !online()) return;
    const unsigned long long now = SDL_GetTicks64();
    if (!since) since = now;
    if (step == 0 && now - since >= 5000ull) {
        push_key(SDL_SCANCODE_T, SDLK_t);
        step = 1;
    } else if (step >= 1 && g_open) {
        if (!opened) opened = now;
        if (step == 1 && now - opened >= 500ull) {
            push_text(text);
            step = 2;
        } else if (step == 2 && now - opened >= 1500ull) {
            push_key(SDL_SCANCODE_RETURN, SDLK_RETURN);
            step = 3;
        }
    }
}

void test_send_tick() {
    test_type_tick();
    static const char* text = std::getenv("LB_CHAT_TEST_SEND");
    static unsigned long long since = 0;
    if (!text || !*text) return;
    if (!online()) return;
    // A negative delay counts from the match's start (states 11 and 12).
    const char* d = std::getenv("LB_CHAT_TEST_DELAY");
    const int secs = d ? std::atoi(d) : 5;
    const int s = lb_net_guest_state();
    if (secs < 0 && s != 11 && s != 12) return;
    const unsigned long long now = SDL_GetTicks64();
    if (!since) since = now;
    const unsigned long long wait = (unsigned long long)(secs < 0 ? -secs : secs) * 1000ull;
    if (now - since < wait) return;
    send(text);
    text = nullptr;
}

