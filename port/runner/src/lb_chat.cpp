// legobattles-decomp: network chat and the swear filter (docs/415).
//
// THE CHAT. Online, in a lobby or a match, the chat key (T by default) opens a
// line at the bottom of the window; Enter sends and closes it, Esc closes it.
// A message travels as its own datagram over the wireless bridge, like the
// host's rules (docs/384): "LBC1", the sender's random origin and a sequence
// number (so a copy that arrives twice is shown once), the sender's hero
// blueprint, its name and the text. Every machine sends to its siblings and
// its remote peer; a HOST also passes on what it receives, so a player
// reaches the others through the host. Nothing here touches the guest: chat
// is not part of the lockstep.
//
// Toasts (on by default) show a received message for a few seconds while the
// chat is closed, led by the sender's hero's battle-HUD icon.
//
// THE SWEAR FILTER (on by default) is applied when text is SHOWN, never when
// it is stored or sent, so switching it off shows every message and name as
// it was written, at once. A match becomes "ziff", or "ziffing" when it ends
// in -ing, in the case of what it replaces (ziff, Ziff, ZIFF). The words are
// not in this repository: lb_chat_words.h holds only salted hashes of them,
// generated by a tool from a list kept elsewhere. Two kinds:
//   * roots, matched anywhere inside a word ("...face", "mother...");
//   * words, matched as a whole word, also with a plural, -ed, -er(s), -in,
//     -ing or -y ending taken off, and with repeated letters collapsed.
// Before matching, look-alike characters read as letters (4 @ -> a, 3 -> e,
// 1 ! -> i, 0 -> o, 5 $ -> s, 7 + -> t).

