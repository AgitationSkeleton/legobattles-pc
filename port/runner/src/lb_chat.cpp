extern "C" int lb_swear_filter(const char* in, char* out, int cap) {
    if (!out || cap <= 0) return 0;
    const std::string s = in ? in : "";
    const std::string f = filter(s);
    std::snprintf(out, (size_t)cap, "%s", f.c_str());
    return f != s ? 1 : 0;
}

extern "C" const char* lb_swear_shown(const char* in) {
    // For a caller that shows a string at once (the lobby browser): the
    // filtered copy lives until the next call on this thread.
    static thread_local std::string s;
    s = shown(in ? in : "");
    return s.c_str();
}

extern "C" int lb_chat_online(void) { return online() ? 1 : 0; }
extern "C" int lb_chat_is_open(void) { return g_open ? 1 : 0; }
extern "C" void lb_chat_open(void) {
    if (!online()) return;
    g_open = true;
    g_focus = true;
    std::fprintf(stderr, "[lb_chat] the chat box opened\n");
    std::fflush(stderr);
    // LB_CHAT_TEST_TYPE: the opening key's own "t" follows its key event, as
    // a keyboard's does, to be swallowed (test_type_tick types the rest).
    static bool typed = false;
    if (std::getenv("LB_CHAT_TEST_TYPE") && !typed) {
        typed = true;
        push_text("t");
    }
}
extern "C" void lb_chat_close(void) {
    g_open = false;
    g_line[0] = '\0';
}

extern "C" int lb_chat_outgoing(unsigned char* buf, int cap) {
    std::lock_guard<std::mutex> lk(g_mu);
    if (g_outbox.empty()) return 0;
    std::vector<uint8_t> d = std::move(g_outbox.front());
    g_outbox.pop_front();
    if ((int)d.size() > cap) return 0;
    std::memcpy(buf, d.data(), d.size());
    return (int)d.size();
}

extern "C" void lb_chat_incoming(const unsigned char* buf, int len,
                                 unsigned int sender) {
    (void)sender;
    if (!buf || len < 16 || std::memcmp(buf, "LBC1", 4) != 0) return;
    if (!online()) return;
    auto le32 = [&](int at) {
        return (uint32_t)buf[at] | ((uint32_t)buf[at + 1] << 8) |
               ((uint32_t)buf[at + 2] << 16) | ((uint32_t)buf[at + 3] << 24);
    };
    const uint32_t o = le32(4), s = le32(8);
    const int hero = buf[12] | (buf[13] << 8);
    int at = 14;
    const int nl = buf[at++];
    if (nl > (int)kNameMax || at + nl + 1 > len) return;
    Msg m;
    m.name.assign((const char*)buf + at, (size_t)nl);
    at += nl;
    const int tl = buf[at++];
    if (tl > (int)kTextMax || at + tl > len) return;
    m.text.assign((const char*)buf + at, (size_t)tl);
    for (char& c : m.name) if ((unsigned char)c < 0x20) c = ' ';
    for (char& c : m.text) if ((unsigned char)c < 0x20) c = ' ';
    m.hero = hero == 0xFFFF ? -1 : hero;
    m.at = SDL_GetTicks64();
    std::lock_guard<std::mutex> lk(g_mu);
    if (o == origin() || seen(o, s)) return;
    if (hosting()) g_outbox.emplace_back(buf, buf + len);   // pass it on
    log_line("from", m);
    add(std::move(m));
}

// Once a frame, inside the overlay's ImGui frame.
extern "C" void lb_chat_draw(SDL_Renderer* r) {
    test_send_tick();
    if (g_open && !online()) lb_chat_close();
    const ImGuiViewport* vp = ImGui::GetMainViewport();
    const float fs = ImGui::GetFontSize();
    std::vector<Msg> recent;
    {
        std::lock_guard<std::mutex> lk(g_mu);
        const unsigned long long now = SDL_GetTicks64();
        if (g_open) {
            const size_t k = g_log.size() > 10 ? g_log.size() - 10 : 0;
            recent.assign(g_log.begin() + (long)k, g_log.end());
        } else if (lb_setting_chat_toasts()) {
            for (const Msg& m : g_log)
                if (!m.mine && now - m.at < 6000ull) recent.push_back(m);
            if (recent.size() > 4) recent.erase(recent.begin(), recent.end() - 4);
        }
    }
    const ImGuiWindowFlags base = ImGuiWindowFlags_NoDecoration |
                                  ImGuiWindowFlags_AlwaysAutoResize |
                                  ImGuiWindowFlags_NoSavedSettings |
                                  ImGuiWindowFlags_NoNav;
    if (!g_open) {
        if (recent.empty()) return;
        // Toasts, top right, newest at the bottom.
        ImGui::SetNextWindowPos(ImVec2(vp->Pos.x + vp->Size.x - 16.0f, vp->Pos.y + 48.0f),
                                ImGuiCond_Always, ImVec2(1.0f, 0.0f));
        ImGui::SetNextWindowBgAlpha(0.80f);
        if (ImGui::Begin("##lb_chat_toasts", nullptr,
                         base | ImGuiWindowFlags_NoInputs |
                             ImGuiWindowFlags_NoFocusOnAppearing)) {
            for (const Msg& m : recent) message_line(r, m, fs * 1.6f, fs * 24.0f);
        }
        ImGui::End();
        return;
    }
    // The chat box, bottom left.
    ImGui::SetNextWindowPos(ImVec2(vp->Pos.x + 16.0f, vp->Pos.y + vp->Size.y - 16.0f),
                            ImGuiCond_Always, ImVec2(0.0f, 1.0f));
    ImGui::SetNextWindowBgAlpha(0.85f);
    if (ImGui::Begin("##lb_chat", nullptr,
                     ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_NoSavedSettings |
                         ImGuiWindowFlags_AlwaysAutoResize)) {
        for (const Msg& m : recent) message_line(r, m, fs * 1.4f, fs * 28.0f);
        if (recent.empty()) ImGui::TextDisabled("Say something to the lobby.");
        ImGui::Separator();
        if (g_focus) {
            ImGui::SetKeyboardFocusHere();
            g_focus = false;
        }
        ImGui::PushItemWidth(fs * 28.0f);
        if (ImGui::InputText("##line", g_line, sizeof g_line,
                             ImGuiInputTextFlags_EnterReturnsTrue)) {
            send(g_line);
            lb_chat_close();
        }
        ImGui::PopItemWidth();
        ImGui::TextDisabled("Enter sends, Esc closes");
    }
    ImGui::End();
}

// LB_SWEAR_SELFTEST="text|text|..." prints each text filtered, once, at the
// first frame. The texts come from the command line, never from the repo.
extern "C" void lb_swear_selftest_if_asked(void) {
    static bool done = false;
    if (done) return;
    done = true;
    const char* p = std::getenv("LB_SWEAR_SELFTEST");
    if (!p) return;
    std::string cur;
    int n = 0, changed = 0;
    for (;; ++p) {
        if (*p == '|' || !*p) {
            if (!cur.empty()) {
                const std::string f = filter(cur);
                ++n;
                if (f != cur) ++changed;
                std::fprintf(stderr, "[lb_swear] %s -> %s\n",
                             f != cur ? "changed" : "kept   ", f.c_str());
            }
            cur.clear();
            if (!*p) break;
        } else {
            cur += *p;
        }
    }
    std::fprintf(stderr, "[lb_swear] self-test: %d of %d changed\n", changed, n);
    std::fflush(stderr);
}
