#!/usr/bin/env bash
# Build the LEGO Battles runner without touching upstream ndsrecomp.
#
#   ./port/runner/build.sh
#
# The upstream tree at $NDSRECOMP is treated as READ-ONLY. This script
# assembles a build tree under port/runner/tree/, copies this port's own
# sources into it, applies the overlay hooks with apply_hooks.py, and builds.
# Every change this port makes to the runner therefore lives in
# legobattles-decomp and is reviewable here; upstream stays pristine and can be
# re-fetched or updated without losing anything.
#
# tree/ and build/ are gitignored: they are assembled output, not source.
set -eu

W="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# ndsrecomp and Dear ImGui: NDSRECOMP and IMGUI, else under LB_TOOLS, else a
# tools/ folder three levels above this checkout (beside the game folders).
TOOLS="${LB_TOOLS:-$W/../../../tools}"
NDSRECOMP="${NDSRECOMP:-$TOOLS/ndsrecomp}"
# The lifted title code (557 MB, made from the ROM, never committed) is
# $W/port/generated unless LB_GENERATED_DIR names another copy -- how a release
# build in a fresh checkout reuses the one already lifted (docs/394).
IMGUI="${IMGUI:-$TOOLS/imgui}"
ROM_SHA1="da60469bd143eb8f47ecf0d7951181b4783c91b4"

TREE="$W/port/runner/tree"
BUILD="$W/port/runner/build"
export PATH="/c/msys64/ucrt64/bin:$PATH"

for d in "$NDSRECOMP/runner" "$IMGUI/backends"; do
    [ -d "$d" ] || { echo "missing: $d"; exit 1; }
done

echo "== assembling build tree =="
# -p preserves mtimes so make can rebuild incrementally. Without it every
# run re-stamps 3.7 MB of unchanged sources and a one-line overlay edit
# costs a full twenty-minute rebuild.
rm -rf "$TREE"
mkdir -p "$TREE"
# The runner's CMakeLists reaches out to ../cmake and ../recompiler, so those
# must sit beside it. ../generated is 6.5 MB of BIOS banks and is pointed at
# in place with NDS_GENERATED_DIR instead of being copied.
for d in cmake recompiler runner vendor tools; do
    [ -d "$NDSRECOMP/$d" ] && cp -rp "$NDSRECOMP/$d" "$TREE/$d"
done
cp -p "$W/port/runner/src/lb_overlay.h"   "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_overlay.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_patches.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_net.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_balance.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_balance_data.h" "$TREE/runner/src/"
# Generated by tools/lb_gen_fxvtables.py from the RTTI extract.
cp -p "$W/port/runner/src/lb_fxvtables.h" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_hud.cpp" "$TREE/runner/src/"
# Its own TU on purpose: <windows.h> must not reach lb_overlay.cpp.
cp -p "$W/port/runner/src/lb_filedlg.cpp" "$TREE/runner/src/"
# The LB_SAMPLE profiler (docs/349). Its own TU for the same <windows.h> reason.
cp -p "$W/port/runner/src/lb_prof.cpp" "$TREE/runner/src/"
# The event pump on its own fiber (docs/385). Its own TU for <windows.h> too.
cp -p "$W/port/runner/src/lb_winloop.cpp" "$TREE/runner/src/"
# Level Palettes (docs/387) and the FactionWars differences it bundles.
cp -p "$W/port/runner/src/lb_palette.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_palette_data.h" "$TREE/runner/src/"
# Mod maps from a mods folder (docs/391).
cp -p "$W/port/runner/src/lb_mods.cpp" "$TREE/runner/src/"
# Online chat and the swear filter (docs/415); the words only as hashes.
cp -p "$W/port/runner/src/lb_chat.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_chat_words.h" "$TREE/runner/src/"
# HTTPS for the master server (docs/419). Its own TU for <windows.h>.
cp -p "$W/port/runner/src/lb_https.cpp" "$TREE/runner/src/"
# A host's mod map from the community archive (docs/420).
cp -p "$W/port/runner/src/lb_mapfetch.cpp" "$TREE/runner/src/"
# The host-level WH: smooth online play (docs/423).
cp -p "$W/port/runner/src/lb_vwh.cpp" "$TREE/runner/src/"
# The master server's relay (docs/424).
cp -p "$W/port/runner/src/lb_relay.cpp" "$TREE/runner/src/"
# The notification sound, on its own audio device (docs/427).
cp -p "$W/port/runner/src/lb_sfx.cpp" "$TREE/runner/src/"
# Post-match statistics for the high-score table (SG-0018).
cp -p "$W/port/runner/src/lb_scores.cpp" "$TREE/runner/src/"
# The picture of a match for the Discord log (docs/428).
cp -p "$W/port/runner/src/lb_matchpic.cpp" "$TREE/runner/src/"
# Map bans, per-map unit bans, Random maps, ban presets (docs/429).
cp -p "$W/port/runner/src/lb_mapbans.cpp" "$TREE/runner/src/"
# Discord Rich Presence over the local IPC pipe (docs/430, SG-0020).
cp -p "$W/port/runner/src/lb_discord.cpp" "$TREE/runner/src/"
# A host sends a joiner its mod map (docs/432).
cp -p "$W/port/runner/src/lb_maptx.cpp" "$TREE/runner/src/"
# Download and install a release in place (docs/435).
cp -p "$W/port/runner/src/lb_update.cpp" "$TREE/runner/src/"
# The first-run setup: the player's own ROM, Europe or USA (docs/394).
cp -p "$W/port/runner/src/lb_setup.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_music.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_demo.cpp" "$TREE/runner/src/"
# Team Builder and Ban Units (docs/384): the ROM reader, the head sheet, the
# army record, the Custom/Random opponent and the ban rules.
cp -p "$W/port/runner/src/lb_teams.cpp" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_wide2d.inc" "$TREE/runner/src/"
# 3D resolution (docs/433): the hi-res partner renderer, its compositing and
# its presentation. Includes, so no source list entry.
cp -p "$W/port/runner/src/lb_hires_soft.inc" "$TREE/runner/vendor/melonds/"
cp -p "$W/port/runner/src/lb_hires_comp.inc" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_hires_front.inc" "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_field.h"   "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_field.cpp" "$TREE/runner/src/"
# The map-space visibility record (docs/247). Its own TU so that deleting
# lb_widemap.cpp in phase 4 does not take the fog reader with it.
cp -p "$W/port/runner/src/lb_fog.h"   "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_fog.cpp" "$TREE/runner/src/"
# THE DECOMPILATION ITSELF, staged into the runner so the runner can grade it.
# src/battles/ is the native port's source and has no other build; compiling it
# here is what makes an A/B replay possible (docs/333). It is copied, not
# symlinked, because apply_hooks rewrites the tree and must not reach back.
cp -p "$W/port/runner/src/lb_shadow.h"   "$TREE/runner/src/"
cp -p "$W/port/runner/src/lb_shadow.cpp" "$TREE/runner/src/"
mkdir -p "$TREE/runner/src/battles"
cp -p "$W/src/battles/types.h"    "$TREE/runner/src/battles/"
cp -p "$W/src/battles/mem.h"      "$TREE/runner/src/battles/"
cp -p "$W/src/battles/registry.c" "$TREE/runner/src/battles/"
cp -p "$W/src/battles/divmod.c"   "$TREE/runner/src/battles/"
cp -p "$W/src/battles/leaf.c"     "$TREE/runner/src/battles/"
cp -p "$W/src/battles/softfloat.c" "$TREE/runner/src/battles/"
cp -p "$W/port/runner/src/lb_widemap.cpp" "$TREE/runner/src/"
echo "  copied cmake recompiler runner vendor tools; added lb_overlay.{h,cpp}"

echo
echo "== applying hooks =="
python "$W/port/runner/apply_hooks.py" "$TREE/runner" "$IMGUI"

echo
echo "== configuring =="
# NDS_BOOTSTRAP_FIRMWARE=ON is REQUIRED, not a preference.
#
# With it off, CMakeLists globs ${GEN}/fw_*.c for the firmware banks.
# ndsrecomp/generated contains NONE of those files, and an empty glob is not a
# CMake error -- it is just an empty list. main.cpp's references to
# g_dispatch_fw_arm9_early and thirteen siblings are guarded by
# "#ifndef NDS_BOOTSTRAP_FIRMWARE", so with the flag off they are compiled with
# nothing to satisfy them and the build dies at link, ten minutes in, with
# fourteen undefined symbols. Turning it ON both empties the glob deliberately
# and adds the compile definition at CMakeLists:512 that removes the
# references. Same shape as docs/91: a filter that matches nothing is accepted
# in silence.
mkdir -p "$BUILD"
cmake -G "Unix Makefiles" -DCMAKE_BUILD_TYPE=Release \
      -DCMAKE_CXX_COMPILER=/c/msys64/ucrt64/bin/g++.exe \
      -DCMAKE_C_COMPILER=/c/msys64/ucrt64/bin/gcc.exe \
      -DNDS_BOOTSTRAP_FIRMWARE=ON \
      -DNDS_GENERATED_DIR="$NDSRECOMP/generated" \
      -DNDS_TITLE_BANK_DIR="${LB_GENERATED_DIR:-$W/port/generated}" \
      -DNDS_TITLE_ROM_SHA1="$ROM_SHA1" \
      -S "$TREE/runner" -B "$BUILD" > "$BUILD/configure.log" 2>&1 || {
    echo "configure FAILED - tail of $BUILD.configure.log:"; tail -25 "$BUILD/configure.log"; exit 1; }
echo "  ok"

echo
echo "== building =="
# LB_JOBS caps the parallelism, because the peak is memory and not CPU.
#
# The generated ARM9 banks are enormous recompiled C, and cc1 takes over a
# GB on the larger ones -- six at once wants more than this machine has
# spare once an emulator or two has been left running. The failure mode is
# nasty precisely because it is not a compile error: the kernel kills cc1,
# make stops, and build.sh greps the log for "error" and finds none, so it
# reports "build FAILED" with nothing after it. Three builds died at 13%
# that way before the cause was looked for.
#
# The default was 6 while port/generated was 214 MB in 13 MB shards. docs/263
# lifted the 32% of the ARM9 the finder had been dropping, which took it to
# 551 MB in 43 MB shards, and apply_hooks now builds them at -O3. Two at a
# time is what that fits in. Raise it only after checking free memory.
JOBS="${LB_JOBS:-2}"
cmake --build "$BUILD" --target nds_runner -j "$JOBS" > "$BUILD/build.log" 2>&1 || {
    echo "build FAILED - errors from $BUILD.build.log:"
    tail -5 "$BUILD/build.log"
    echo "(if nothing above looks like a compile error, the compiler was"
    echo " probably killed for memory -- retry with LB_JOBS=2)"
    grep -iE "error" "$BUILD/build.log" | head -20; exit 1; }

echo "  ok"
ls -la "$BUILD/nds_runner.exe"

# DEPLOY, so the playable copy can never go stale.
#
# This is the systemic fix for the worst failure this project has had.
# build/LegoBattles.exe was tested for days while every "verified" fix went into
# port/runner/build/nds_runner.exe and nothing copied one to the other: the
# deployed binary was dated 2026-09-03 and HEAD was 233 commits ahead of it, so
# lb_music.cpp did not even exist in the program being tested. Three of ten
# reported defects were about code that had already been written.
#
# Only refreshes a deployment that already exists -- it will not create one --
# and LB_NO_DEPLOY=1 skips it, which is what you want while the deployed
# game is open, since Windows will not let a running .exe be overwritten.
if [ -z "${LB_NO_DEPLOY:-}" ] && [ -f "$W/build/LegoBattles.exe" ]; then
    if python "$W/tools/lb_deploy.py" > "$BUILD/deploy.log" 2>&1; then
        echo "  deployed -> build/LegoBattles.exe"
    else
        echo "  NOT deployed (see $BUILD/deploy.log) -- build/LegoBattles.exe"
        echo "  is now OLDER than the runner you just built."
        tail -3 "$BUILD/deploy.log"
    fi
fi
